# Operaciones matemáticas con python
# Son muy similares a otros lenguajes

print(2 + 2, "Suma")
print(56 - 2, "Resta")
print(2 * 2, "Multiplicación")
print(9 / 3, "División - Esto retorna un valor flotante")

print(2**3, "Potencia")
print(29 // 3, "División sin decimales")
print(7 % 3, "Módulo - Lo que sobra de la división con enteros")

print(101 & 1110, "División binaria")

# Redondea a valor más cercano
print(round(3.2))  # 3
print(round(3.9))  # 4

# Valor absoluto

print(abs(-20))  # 20
