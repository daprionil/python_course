# Métodos de eliminación
numbers = [1, 2, 3, 3, 4, 5]

# pop - Elimina el último elemento de una lista o el elemento del índice que le pasemos
numbers.pop()
numbers.pop(0)

# remove - Le pasamos el valor que queremos eliminar, y va a eliminar el primero que encuentre.
numbers.remove(3)

# clear
numbers.clear()

print(numbers)
