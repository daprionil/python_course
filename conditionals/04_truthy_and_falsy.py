# Valores verdaderos

# Todo número diferente a 0 es verdadero
print(bool(1))
print(bool(-1))
print(bool(1j))
print(bool("a"))
print(bool([1, 2, 3]))
print(bool({1, 2, 3}))
print(bool(True))

# Valores falsos
print(bool(""))
print(bool(0))
print(bool([]))
print(bool({}))
print(bool(()))
print(bool(None))
