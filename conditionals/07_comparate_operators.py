# Operadores de comparación

# Operador de igualdad - Nos permite comparar si son iguales
print(5 == 5)  # True
print(3 == 5)  # False
print("Hello" == "Hello")  # True

# Operador de desigualdad
print(3 != 5)  # True
print(5 != 5)  # False
print("Hello" != "Hello")  # False

# Operador > ó <
print(3 < 5)  # True
print(9 > 5)  # True
print(9 >= 9)  # True
print(3 <= 9)  # True
